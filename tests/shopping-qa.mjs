import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {mkdtempSync,mkdirSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
const dataDir=mkdtempSync(resolve(tmpdir(),'mvn-shopping-'));
const reportDir='reports/visual-qa/shopping';
mkdirSync(reportDir,{recursive:true});
const base='http://localhost:34997';
const child=spawn(process.execPath,['server.mjs'],{cwd:resolve('.'),env:{...process.env,PORT:'34997',PUBLIC_ORIGIN:base,DATA_DIR:dataDir,STAGING_MODE:'false',NODE_ENV:'test'},stdio:['ignore','pipe','pipe']});
let browser;
try{
 await new Promise((ok,no)=>{const timer=setTimeout(()=>no(Error('server startup timed out')),5000);child.stdout.once('data',()=>{clearTimeout(timer);ok()});child.once('exit',()=>{clearTimeout(timer);no(Error('server exited'))});child.once('error',no)});
 browser=await chromium.launch({...(process.env.CHROMIUM_EXECUTABLE_PATH?{executablePath:process.env.CHROMIUM_EXECUTABLE_PATH}:{}),args:['--no-sandbox']});
 for(const width of [1440,390,320]){
 const page=await browser.newPage({viewport:{width,height:950}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/');
 await page.locator('#priceRange').selectOption('under1000');
 assert.equal(await page.locator('#grid .card').count(),2);
 await page.locator('#priceRange').selectOption('1000to3000');
 assert.equal(await page.locator('#grid .card').count(),2);
 assert.match(await page.locator('#v-mass option:checked').textContent(),/3 kg/);
 assert.match(await page.locator('#price-mass').textContent(),/2,599/);
 await page.locator('#resetFilters').click();
 await page.locator('#sort').selectOption('high');
 assert.match(await page.locator('#grid .card').first().textContent(),/Potency Whey/);
 await page.locator('#q').fill('zzzz-no-match');
 assert.equal(await page.getByRole('heading',{name:'No matching products'}).count(),1);
 await page.getByRole('button',{name:'View all products'}).click();
 assert.equal(await page.locator('#grid .card').count(),5);
 await page.locator('#q').fill('<img src=x onerror=alert(1)>');
 assert.equal(await page.locator('#activeFilters img').count(),0);
 await page.locator('#resetFilters').click();
 await page.locator('.cats [data-cat="mass"]').click();
 assert.equal(await page.locator('#grid .card').count(),1);
 await page.locator('.nav [data-cat="all"]').click();
 assert.equal(await page.locator('#grid .card').count(),5);
 await page.locator('[data-detail="whey"]').click();
 await page.locator('#detailClose').click();
 assert.equal(await page.locator('#recentProducts button').count(),1);
 await page.reload();
 assert.equal(await page.locator('#recentProducts button').count(),1);
 await page.locator('.add[data-id="whey"]').click();
 assert.equal(await page.locator('#close').evaluate(el=>el===document.activeElement),true);
 assert.equal(await page.locator('main').evaluate(el=>el.inert),true);
 await page.keyboard.press('Shift+Tab');
 assert.equal(await page.locator('#send').evaluate(el=>el===document.activeElement),true);
 await page.keyboard.press('Tab');
 assert.equal(await page.locator('#close').evaluate(el=>el===document.activeElement),true);
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('main').evaluate(el=>el.inert),false);
 assert.equal(await page.locator('.add[data-id="whey"]').evaluate(el=>el===document.activeElement),true);
 await page.locator('#shop').scrollIntoViewIfNeeded();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,`overflow at ${width}`);
 await page.screenshot({path:`${reportDir}/collection-${width}.png`,fullPage:false});
 await page.locator('#clearRecent').click();
 assert.equal(await page.locator('#recentSection').isVisible(),false);
 assert.deepEqual(errors,[]);
 await page.close();console.log('PASS collection search, price/pack selection, sorting, categories, history, cart keyboard/focus, layout at '+width);
 }
}finally{await browser?.close();if(child.exitCode===null){const stopped=new Promise(done=>child.once('exit',done));child.kill();await stopped;}rmSync(dataDir,{recursive:true,force:true});}
